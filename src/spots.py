def congestion_level(ratio: float) -> str:
    """수용력 대비 방문객 비율 → 혼잡도 단계."""
    if ratio < 0.4:
        return "여유"
    if ratio < 0.7:
        return "보통"
    if ratio < 1.0:
        return "약간 혼잡"
    return "혼잡"
